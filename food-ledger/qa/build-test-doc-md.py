def esc(text):
    """表格单元格里不能有裸的竖线与换行。"""
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(c) for c in r) + " |")
    return "\n".join(out)



def sheet_cases(wb):
    ws = wb.create_sheet("测试用例")
    for i, (name, width) in enumerate(COLUMNS, start=1):
        col = get_column_letter(i)
        ws.column_dimensions[col].width = width
        ws.cell(row=1, column=i, value=name)
    style_header(ws, 1, len(COLUMNS))
    ws.row_dimensions[1].height = 28

    module_fill = {}
    r = 2
    for row in CASES:
        for c, value in enumerate(row, start=1):
            cell = ws.cell(row=r, column=c, value=value)
            cell.alignment = WRAP
            cell.border = BORDER
        lvl = row[2]
        fill = {"P0": P0_FILL, "P1": P1_FILL, "P2": P2_FILL}[lvl]
        ws.cell(row=r, column=3).fill = fill
        ws.cell(row=r, column=3).alignment = CENTER
        ws.cell(row=r, column=1).alignment = CENTER
        # 模块列给个底色，便于分段查看
        if row[1] not in module_fill:
            module_fill[row[1]] = len(module_fill) % 2 == 0
        if module_fill[row[1]]:
            ws.cell(row=r, column=2).fill = PatternFill("solid", fgColor="F7FBF7")
        r += 1

    last = r - 1
    ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(COLUMNS)), last)
    ws.freeze_panes = "D2"

    dv = DataValidation(type="list", formula1='"通过,不通过,阻塞,未执行"', allow_blank=True,
                        showDropDown=False)
    dv.error = "请从下拉中选择"
    dv.prompt = "选择执行结论"
    ws.add_data_validation(dv)
    dv.add("J2:J%d" % last)

    dv2 = DataValidation(type="list", formula1='"P0,P1,P2"', allow_blank=True)
    ws.add_data_validation(dv2)
    dv2.add("C2:C%d" % last)
    return ws, last


def sheet_summary(wb, last):
    ws = wb.create_sheet("执行汇总")
    ws.column_dimensions["A"].width = 26
    for col in "BCDEF":
        ws.column_dimensions[col].width = 12

    ws["A1"] = "执行汇总（自动统计「测试用例」页，无需手填）"
    ws["A1"].font = TITLE_FONT
    ws.merge_cells("A1:F1")

    heads = ["模块", "用例数", "P0 数", "通过", "不通过", "未执行/阻塞"]
    for i, h in enumerate(heads, start=1):
        ws.cell(row=3, column=i, value=h)
    style_header(ws, 3, len(heads))

    modules = []
    for row in CASES:
        if row[1] not in modules:
            modules.append(row[1])

    r = 4
    for mod in modules:
        ws.cell(row=r, column=1, value=mod)
        ws.cell(row=r, column=2, value='=COUNTIF(测试用例!$B$2:$B$%d,A%d)' % (last, r))
        ws.cell(row=r, column=3, value='=COUNTIFS(测试用例!$B$2:$B$%d,A%d,测试用例!$C$2:$C$%d,"P0")'
                % (last, r, last))
        ws.cell(row=r, column=4, value='=COUNTIFS(测试用例!$B$2:$B$%d,A%d,测试用例!$J$2:$J$%d,"通过")'
                % (last, r, last))
        ws.cell(row=r, column=5, value='=COUNTIFS(测试用例!$B$2:$B$%d,A%d,测试用例!$J$2:$J$%d,"不通过")'
                % (last, r, last))
        ws.cell(row=r, column=6, value='=COUNTIFS(测试用例!$B$2:$B$%d,A%d,测试用例!$J$2:$J$%d,"阻塞")'
                '+COUNTIFS(测试用例!$B$2:$B$%d,A%d,测试用例!$J$2:$J$%d,"未执行")'
                % (last, r, last, last, r, last))
        for c in range(1, 7):
            ws.cell(row=r, column=c).border = BORDER
            if c > 1:
                ws.cell(row=r, column=c).alignment = CENTER
        r += 1

    # 合计行
    ws.cell(row=r, column=1, value="合计")
    for c in range(2, 7):
        col = get_column_letter(c)
        ws.cell(row=r, column=c, value="=SUM(%s4:%s%d)" % (col, col, r - 1))
    for c in range(1, 7):
        cell = ws.cell(row=r, column=c)
        cell.font = Font(bold=True)
        cell.border = BORDER
        cell.fill = PatternFill("solid", fgColor="EAF3EA")
        if c > 1:
            cell.alignment = CENTER

    ws.cell(row=r + 2, column=1, value="判定标准：P0 全部通过 → 本轮通过；任一 P0 不通过 → 本轮不通过")
    ws.cell(row=r + 3, column=1, value="填完「结论」列后，本页数字会自动更新（用 Excel/WPS 打开）")
    return ws


